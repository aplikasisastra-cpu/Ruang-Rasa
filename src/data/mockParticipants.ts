export function generateInitialParticipants(currentUserName: string): Participant[] {
  // Current user is participant #1 (Host)
  const host: Participant = {
    id: 'user-host-local',
    name: `${currentUserName} (Anda)`,
    role: 'host',
    avatarBg: 'bg-blue-600 text-white',
    isMuted: false,
    isVideoOn: true,
    isHandRaised: false,
    connectionQuality: 'excellent',
    isSpeaking: false,
    city: 'Pusat Rapat',
  };

  const peers: Participant[] = rawNames.slice(0, 99).map((person, index) => {
    const isCoHost = index === 0 || index === 3;
    const isMuted = index % 3 !== 0; // ~66% muted (natural in 100-person meetings)
    const isVideoOn = index % 4 !== 0; // ~75% video on
    const isHandRaised = index === 2 || index === 8 || index === 14;

    return {
      id: `participant-${index + 1}`,
      name: person.name,
      role: isCoHost ? 'co-host' : 'participant',
      avatarBg: bgColors[index % bgColors.length],
      isMuted,
      isVideoOn,
      isHandRaised,
      connectionQuality: index % 17 === 0 ? 'good' : 'excellent',
      isSpeaking: false,
      city: person.city,
    };
  });

  return [host, ...peers];
}
